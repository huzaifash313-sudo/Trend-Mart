export default function DashboardSidebarNav({
  dineIn = false,
  onNavigate,
  compact = false,
}: {
  dineIn?: boolean;
  onNavigate?: () => void;
  compact?: boolean;
}) {
  const pathname = usePathname();
  const items = filterMerchantNav(MERCHANT_NAV, dineIn);

  return (
    <nav className="space-y-0.5" aria-label="Merchant dashboard">
      {items.map((item) => {
        const active = isMerchantNavActive(pathname, item.href);
        const indigo = item.accent === "indigo";
        return (
          <Link
            key={item.href}
            href={item.href}
            onClick={onNavigate}
            className={`flex items-start gap-2.5 rounded-xl px-2.5 py-2 transition-colors ${
              active
                ? indigo
                  ? "bg-indigo-50 text-indigo-700 dark:bg-indigo-900/25 dark:text-indigo-300"
                  : "bg-emerald-50 text-emerald-700 dark:bg-emerald-900/20 dark:text-emerald-400"
                : indigo
                  ? "text-indigo-600 hover:bg-indigo-50/80 dark:text-indigo-400 dark:hover:bg-indigo-900/15"
                  : "text-zinc-600 hover:bg-zinc-100 dark:text-zinc-300 dark:hover:bg-zinc-800"
            }`}
          >
            <span
              className={`mt-0.5 flex h-7 w-7 shrink-0 items-center justify-center rounded-lg ${
                active
                  ? indigo
                    ? "bg-indigo-100 dark:bg-indigo-900/40"
                    : "bg-emerald-100 dark:bg-emerald-900/40"
                  : "bg-zinc-100 dark:bg-zinc-800"
              }`}
            >
              <NavGlyph href={item.href} />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-[13px] font-semibold leading-tight">
                {item.label}
              </span>
              {!compact ? (
                <span className="mt-0.5 block text-[10px] font-medium leading-tight text-zinc-400 dark:text-zinc-500">
                  {item.blurb}
                </span>
              ) : null}
            </span>
          </Link>
        );
      })}
    </nav>
  );
}
